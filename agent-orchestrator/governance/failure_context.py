"""Deterministic failure evidence; classification never grants write permission."""
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

from governance.rollback_manager import file_hash
from governance.source_policy import authorized_java_target


RECOVERABLE = {'model_output', 'source_edit_conflict', 'java_compilation', 'test_assertion'}


def classify_failure(error_type='', message='', validation=None):
    output = (validation or {}).get('output', '')
    text = (message + '\n' + output).lower()
    if error_type == 'RecoveryRequired' or any(word in text for word in (
        'source changed', 'source verification failed', 'checkpoint integrity', 'unfinished transaction')):
        return 'source_edit_conflict', False
    if error_type == 'PermissionError':
        return 'authorization', False
    if validation is not None:
        if validation.get('exit_code') == -1 or any(word in text for word in (
            'could not resolve', 'non-resolvable', 'could not transfer', 'permission denied',
            'could not open file', 'connection refused', 'timed out', 'validation could not run')):
            return 'infrastructure', False
        if 'compilation error' in text or 'compilation failure' in text:
            return 'java_compilation', True
        if any(word in text for word in ('there are test failures', 'assertionfailed', 'failures:', 'tests run:')):
            return 'test_assertion', True
        return 'infrastructure', False
    if error_type in {'JSONDecodeError', 'ValidationError', 'TypeError'}:
        return 'model_output', True
    if error_type == 'ValueError':
        if 'expected source text' in text or 'overlapping' in text:
            return 'source_edit_conflict', True
        return 'model_output', True
    return 'infrastructure', False


def collect_failure(state, *, current_hashes=None):
    """Use current-attempt data only. Keep prior diagnostics separate."""
    validation = state.get('validation_result') if state.get('status') == 'VALIDATION_FAILED' else None
    category, recoverable = classify_failure(state.get('implementation_error_type', ''),
                                            state.get('implementation_error', ''), validation)
    transaction = state.get('implementation_transaction', {})
    proposal = transaction.get('proposal') or state.get('implementation_proposal', {})
    details = state.get('implementation_attempt_details', {})
    attempt = state.get('retry_count', 0) + 1
    tasks = state.get('tasks', [])
    approved = [task for task in tasks if task['task_id'] in state.get('active_task_ids', [])]
    hashes = {}
    hash_errors = {}
    for task in approved:
        for relative in task['allowed_files']:
            try:
                target = authorized_java_target(relative, Path(state['workspace']), task['allowed_files'])
                hashes[relative] = file_hash(target.read_bytes())
            except Exception as error:
                hash_errors[relative] = f'{type(error).__name__}: {error}'
    tests = []
    # Only reports generated by the current Maven test invocation are admissible.
    # Compilation failures can leave old reports; never treat them as new evidence.
    if category == 'test_assertion':
        root = Path(state['workspace']).resolve(strict=True)
        reports = root / 'url-shortener/target/surefire-reports'
        for path in sorted(reports.glob('TEST-*.xml')):
            if not path.resolve().is_relative_to(root):
                continue
            try:
                for case in ET.parse(path).getroot().findall('testcase'):
                    for kind in ('failure', 'error'):
                        failure = case.find(kind)
                        if failure is not None:
                            tests.append({'class': case.get('classname'), 'test': case.get('name'),
                                          'kind': kind, 'message': failure.get('message', '')[:4000]})
            except (ET.ParseError, OSError):
                continue
    output = (validation or {}).get('output', '')
    diagnostics = [line for line in output.splitlines() if '[ERROR]' in line or 'Caused by:' in line]
    evidence = {
        'attempt': attempt, 'category': category, 'recoverable': recoverable,
        'error_type': state.get('implementation_error_type', ''),
        'message': state.get('implementation_error', ''),
        'validation': validation or {'passed': False, 'exit_code': None, 'output': state.get('implementation_error', '')},
        'diagnostics': diagnostics, 'test_failures': tests,
        'attempted_edits': proposal, 'raw_response': details.get('raw_response', transaction.get('raw_response', '')),
        'approved_tasks': approved, 'approved_task_hash': state.get('approved_task_hash', ''),
        'transaction_id': transaction.get('transaction_id'),
        'original_hashes': {cp['path']: cp['original_hash'] for cp in transaction.get('checkpoints', [])}
                           or details.get('original_hashes', {}),
        'expected_hashes': transaction.get('expected_hashes', {}),
        'observed_hashes': current_hashes or hashes, 'hash_errors': hash_errors,
    }
    if hash_errors:
        evidence.update(category='source_edit_conflict', recoverable=False)
    evidence['evidence_hash'] = hashlib.sha256(json.dumps(evidence, sort_keys=True).encode()).hexdigest()
    return evidence
